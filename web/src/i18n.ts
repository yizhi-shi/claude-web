import { ref } from 'vue';

export type Locale = 'zh' | 'en';

const STORAGE_KEY = 'cw.locale';

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'zh';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    // localStorage may be unavailable
  }
  const language = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return /^zh\b/i.test(language) ? 'zh' : 'en';
}

export const locale = ref<Locale>(detectLocale());

export function initLocale(): void {
  applyLocale();
}

export function setLocale(next: Locale): void {
  locale.value = next;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // ignore
  }
  applyLocale();
}

export function toggleLocale(): void {
  setLocale(locale.value === 'zh' ? 'en' : 'zh');
}

function applyLocale(): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale.value === 'zh' ? 'zh-CN' : 'en';
  }
}

export function t(source: string, params?: Record<string, string | number>): string {
  let text = locale.value === 'en' ? EN[source] ?? source : source;
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (match, key: string) =>
      params[key] === undefined ? match : String(params[key]),
    );
  }
  return text;
}

/** Translate the handful of server messages that can surface in the UI. */
export function translateServerMessage(message: string): string {
  if (locale.value === 'zh' || !message) return message;
  const exact = SERVER_MESSAGES[message];
  if (exact) return exact;
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^账号已锁定，请 (\d+) 分钟后重试$/, (m) => `Account locked. Try again in ${m[1]} minute(s).`],
    [/^连续多次密码错误，账号已锁定 (\d+) 分钟$/, (m) => `Too many failed attempts. Account locked for ${m[1]} minute(s).`],
    [/^尝试次数过多，请稍后再试$/, () => 'Too many attempts. Try again later.'],
    [/^未登录或会话已过期$/, () => 'Not signed in or session expired.'],
    [/^账号或密码错误$/, () => 'Incorrect username or password.'],
  ];
  for (const [pattern, render] of patterns) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}

